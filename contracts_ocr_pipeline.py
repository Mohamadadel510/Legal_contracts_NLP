"""# الخلية 6: حفظ المخرجات الخام وحماية النسخة الأصلية (Immutable Object)"""

def save_raw_ocr(data, output_dir):
    """حفظ نتائج الـ OCR الخام في ملفات JSON و TXT"""
    raw_json_path = os.path.join(output_dir, "raw_ocr.json")
    with open(raw_json_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    raw_txt_path = os.path.join(output_dir, "raw_ocr.txt")
    lines_by_page = {}
    for item in data:
        lines_by_page.setdefault(item["page"], []).append(item)

    with open(raw_txt_path, "w", encoding="utf-8") as f:
        for page in sorted(lines_by_page.keys()):
            f.write(f"===== صفحة {page} =====\n")
            for item in sorted(lines_by_page[page], key=lambda x: x["line_number"]):
                f.write((item["text"] or "") + "\n")
            f.write("\n")

    return raw_json_path, raw_txt_path

