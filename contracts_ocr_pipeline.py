"""# الخلية 5: استخراج النصوص بـ Gemini (Ext)"""

import pytesseract

def extract_text_local_ocr(pages):
    """استخراج النصوص سطر بسطر محلياً باستخدام Tesseract بدون الحاجة لأي API."""
    raw_ocr_data = []

    # إعدادات Tesseract لقراءة اللغة العربية والإنجليزية
    custom_config = r'--oem 3 --psm 6'

    for page_idx, page_image in enumerate(pages):
        page_number = page_idx + 1
        print(f"جاري معالجة الصفحة {page_number} من {len(pages)} محلياً...")

        try:
            # استخراج النص من الصورة محلياً
            text = pytesseract.image_to_string(page_image, lang='ara+eng', config=custom_config)

            # تقسيم النص الناتج إلى أسطر وتنظيف الفراغات
            lines = [line.strip() for line in text.split('\n') if line.strip()]

            for line_idx, line_text in enumerate(lines):
                line_id = f"p{page_number}_l{line_idx + 1}"
                raw_ocr_data.append({
                    "page": page_number,
                    "line_id": line_id,
                    "line_number": line_idx + 1,
                    "text": line_text,
                    "confidence": 1.0,
                    "bbox": None
                })
        except Exception as e:
            print(f"⚠️ خطأ في معالجة الصفحة {page_number}: {e}")

    return raw_ocr_data

# تشغيل الاستخراج المحلي
