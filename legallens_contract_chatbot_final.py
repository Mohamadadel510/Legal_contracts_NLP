SUPPORTED_MODELS = [
    'gemini-3.6-flash',
    'gemini-3.5-flash',
    'gemini-2.5-flash'
]

MODEL_NAME = None
gemini_contract_file = None

try:
    gemini_contract_file = client.files.upload(
        file=CONTRACT_PATH,
        config=types.UploadFileConfig(
            display_name='LegalLens Original Contract',
            mime_type='application/pdf'
        )
    )
    print('✅ تم تحميل النسخة الأصلية إلى جلسة Gemini بنجاح.')
except Exception as e:
    raise RuntimeError(f'❌ فشل تحميل العقد إلى Gemini: {e}')

# اختيار أول نموذج متاح فعليًا دون إرسال أسئلة للمستخدم
for candidate in SUPPORTED_MODELS:
    try:
        test = client.models.generate_content(
            model=candidate,
            contents='رد بكلمة واحدة فقط: جاهز',
            config=types.GenerateContentConfig(temperature=0.0, max_output_tokens=10)
        )
        if test and getattr(test, 'text', None):
            MODEL_NAME = candidate
            break
    except Exception as e:
        msg = str(e)
        if '429' in msg or 'RESOURCE_EXHAUSTED' in msg:
            # لا نختبر نماذج إضافية إذا كان الحساب نفسه على حد الطلبات.
            MODEL_NAME = candidate
            print(f'⚠️ تم اختيار {candidate} مع وجود Rate Limit حالي؛ سيُستخدم retry تلقائيًا عند السؤال.')
            break
        continue

if MODEL_NAME is None:
    MODEL_NAME = 'gemini-3.6-flash'

