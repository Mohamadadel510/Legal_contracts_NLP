# 5) منطق الشات بوت — إجابة دقيقة من العقد الأصلي فقط

SYSTEM_INSTRUCTION = '''
أنت LegalLens، مساعد لتحليل العقد المرفوع.

قواعد إلزامية:
1) المصدر الوحيد للإجابة هو ملف العقد الأصلي المرفق في الطلب. لا تستخدم الإنترنت ولا المعرفة العامة ولا التخمين.
2) افهم السؤال حتى لو كان مكتوبًا بلهجة مصرية أو بصياغة مختصرة، ثم ابحث عن الإجابة داخل العقد.
3) عند السؤال عن شخص أو طرف أو مبلغ أو رقم شقة/عمارة/دور أو تاريخ أو مدة أو بند، اقرأ الموضع المناسب من العقد بعناية شديدة، ولا تغيّر أي رقم.
4) إذا كانت المعلومة موجودة في العقد، أجب عنها بوضوح وبالعربية، ويمكنك إعادة صياغة الجملة لتكون مفهومة، لكن لا تغيّر معناها أو أرقامها.
5) إذا كانت الإجابة موزعة على أكثر من موضع في العقد، اجمع المعلومات الموجودة في العقد فقط وقدّم إجابة واحدة مرتبة.
6) إذا كان السؤال يتطلب استنتاجًا غير مذكور صراحة في العقد، لا تخمّن. قل: «❌ إجابة هذا السؤال غير موجودة في العقد المرفوع.»
7) إذا سأل المستخدم عن حكم قانوني عام أو معلومة خارج العقد، لا تجب من معرفتك العامة؛ قل: «❌ إجابة هذا السؤال غير موجودة في العقد المرفوع.»
8) إذا كان السؤال خارج موضوع العقد تمامًا، قل: «❌ هذا السؤال خارج نطاق العقد المرفوع.»
9) لا تدّعي أن شيئًا موجود في العقد إذا لم تجده بوضوح.
10) عند وجود أكثر من قيمة متشابهة، ميّز بينها حسب السياق بدل اختيار قيمة عشوائية.
11) اجعل الإجابة مباشرة ومفيدة، ولا تكتب شرحًا تقنيًا عن النموذج أو الـ RAG.
12) في نهاية الإجابة، إذا أمكن تحديد الموضع، أضف: «📄 الصفحة: X».
'''

chat_history = []

def generate_answer(question, max_retries=4):
    question = (question or '').strip()
    if not question:
        return '⚠️ اكتب سؤالًا أولًا.'

    prompt = f'''\
أجب عن السؤال التالي باستخدام العقد الأصلي المرفق فقط.

سؤال المستخدم:
{question}

لا تعتمد على أي معلومة خارج الملف المرفق.
'''

    contents = [gemini_contract_file, prompt]

    for attempt in range(max_retries):
        try:
            response = client.models.generate_content(
                model=MODEL_NAME,
                contents=contents,
                config=types.GenerateContentConfig(
                    system_instruction=SYSTEM_INSTRUCTION,
                    temperature=0.0,
                    max_output_tokens=1200,
                )
            )

            answer = (getattr(response, 'text', '') or '').strip()
            if answer:
                chat_history.append((question, answer))
                return answer
            return '❌ إجابة هذا السؤال غير موجودة في العقد المرفوع.'

        except Exception as e:
            msg = str(e)
            rate_limited = ('429' in msg or 'RESOURCE_EXHAUSTED' in msg or 'quota' in msg.lower())
            if rate_limited and attempt < max_retries - 1:
                wait_seconds = 8 * (2 ** attempt)
                time.sleep(wait_seconds)
                continue

            if rate_limited:
                return '⚠️ تم الوصول إلى حد طلبات Gemini مؤقتًا. انتظر قليلًا ثم أرسل السؤال مرة أخرى.'
            return f'⚠️ حدث خطأ أثناء معالجة السؤال: {msg}'

    return '⚠️ تعذر الحصول على إجابة حاليًا.'

