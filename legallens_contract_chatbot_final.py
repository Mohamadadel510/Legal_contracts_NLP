question_box = widgets.Textarea(
    placeholder='اكتب سؤالك عن العقد هنا...',
    layout=widgets.Layout(width='80%', min_height='70px'),
    style={'description_width': 'initial'}
)

send_button = widgets.Button(
    description='🔍 إرسال',
    button_style='primary',
    layout=widgets.Layout(width='18%', height='70px')
)

def show_message(role, text):
    safe = html.escape(str(text)).replace('\n', '<br>')
    if role == 'user':
        box = '#e8f0fe'
        label = '👤 أنت'
    else:
        box = '#f1f3f4'
        label = '🤖 LegalLens'
    with output_area:
        display(HTML(f'''<div style='direction:rtl;text-align:right;margin:10px 0;'>
        <div style='font-weight:bold;margin-bottom:5px;'>{label}</div>
        <div style='background:{box};padding:12px;border-radius:10px;line-height:1.8;'>{safe}</div>
        </div>'''))

def process_query(_=None):
    question = question_box.value.strip()
    if not question:
        return
    question_box.value = ''
    show_message('user', question)
    answer = generate_answer(question)
    show_message('bot', answer)

send_button.on_click(process_query)

display(title)
display(widgets.HBox([question_box, send_button]))
display(output_area)

print('✅ الشات بوت جاهز لاستقبال الأسئلة.')